# ==== BEGIN K4S CANONICAL SHELL LOADER r1 main (bootstrap-r1/k4s_bootstrap_loader_r1.py = the bootstrap above + this) ====
# Run ONLY as:  /usr/bin/python3 -I -S -c "$k4s_loader" PATH SHA256 SIZE -- ARGS...   (runs the tool as __main__)
#          or:  /usr/bin/python3 -I -S -c "$k4s_loader" PATH SHA256 SIZE --verify-only (checks, executes nothing)
# The interpreter opens no script by path; this loader never reads stdin (a pipe into the tool reaches the tool
# untouched) and creates no file. Refusal: one line on stderr, exit status 90 (the wrapper bootstrap refusal).


def k4s_bootstrap_loader_main(argv):
    import re
    import sys

    def refusal(message):
        sys.stderr.write(message + "\n")
        sys.stderr.flush()
        return SystemExit(90)

    if not (sys.flags.isolated and sys.flags.no_site):
        raise refusal("k4s bootstrap refused: the loader must run under python3 -I -S")
    if (len(argv) < 4 or argv[3] not in ("--", "--verify-only") or (argv[3] == "--verify-only" and len(argv) != 4)
            or not re.fullmatch(r"[1-9][0-9]{0,8}", argv[2])):
        raise refusal("k4s bootstrap refused: usage: PATH SHA256 SIZE -- ARGS... | PATH SHA256 SIZE --verify-only")
    path, sha256, size = argv[0], argv[1], int(argv[2])
    data = k4s_bootstrap_read_verified(path, sha256, size, refusal)
    if argv[3] == "--verify-only":
        return 0
    sys.argv = [path] + list(argv[4:])
    k4s_bootstrap_exec(data, path, sha256, "__main__")
    return 0


raise SystemExit(k4s_bootstrap_loader_main(__import__("sys").argv[1:]))
