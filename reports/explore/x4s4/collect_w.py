"""X4S-4 matched off-policy control O_W (exploration, NEVER ADOPTABLE). r3 after Sol script review r2.

W-screen8 (no deadline) vs the exact v1 policy on the five X decks, generated by the UNCHANGED reviewed
imitation/exit_r1/emitter.py (run_game, opponent='v1'); this wrapper only chooses inputs. For bank C' game g
(seed = C'base + g) it uses the X4S index mapping: own = X[g % 5], opponent = X[(g // 5) % 5], seat = g % 2. The
emitter derives own = decks()[index % 8], other = decks()[(index // 8) % 8], seat = index % 2, so the wrapper passes
index = 56 + seat and, per game, a decks() list with X[own] at position seat and X[opponent] at position 7.

All I/O goes through x4s4io (R2-F1). Outputs: games in <job>/data/raw-OW/game-<g:05d>/ (each directory validated
fresh before the emitter writes it); the selection receipt <job>/data/raw-OW-selection.json binding every selected
game's realized identity (seed, index, seat, own/opponent deck, root count, manifest SHA) and the v1/emitter SHAs;
unselected completed games renamed into <job>/data/raw-OW-unused/.

Acceptance smoke (PLAN §6.6, R2-F5): exactly TWO games on the declared QUALIFICATION bank (4503606337370496 + g,
g = 0, 1), never on C', so they are excluded from O_W by construction; written to <job>/data/raw-OW-acceptance/ and
receipted in <job>/data/raw-OW-acceptance-smoke.json with each game's seed, index, seat, decks, replay_exact, manifest
SHA and the v1/emitter SHAs; verify_onpolicy re-verifies those seals and identities. r4 (R3-F2): each acceptance game
runs in an owned worker process under a polling parent (live guards; breach -> verified worker PIDs stopped); a game
completing after the hard stop is rejected and passed also requires the deadline unmet at the end.

Every game, fresh or resumed, must match its realized identity (seed, index, opponent v1, seat, deck multisets); a
resumed game's seal is re-verified completely. Dispatch stops once the contiguous completed prefix holds >= target
roots (|O| from O-VERIFIED.json); the smallest such prefix is selected.
Live guards (R2-F3): admission reserves workers + 1 processes; between dispatches the parent runs studytree.monitor
(STOP lexists, hard stop, MemAvailable, PSI readability, this run's PSS <= 50 GiB, tree <= 70 processes, job <= 100
GB) and, on a breach, TERM/KILLs its own verified worker PIDs (the unchanged emitter only sees STOP via exists()), so
an in-flight game cannot run on past the hard stop; a game that returns after the hard stop is not counted. No new game
is dispatched while memory PSI avg10 > 10. The process exits 1 if the target is not reached, a game fails, a guard
fires, or the acceptance smoke fails.
"""
import argparse, json, multiprocessing, os, signal, socket, sys, time
from concurrent.futures import ProcessPoolExecutor, FIRST_COMPLETED, wait
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import x4s4io as io, studytree                    # noqa: E402

JOB = io.JOB
V1_SHA = 'd77005d59d6ed40ce7f9bfcfde569b54958bebf056e00653b10dcee3957272ed'
EMITTER_SHA = 'dab616517ea6b33ae1de6a34909526cf5409ec4ad71c180188d95d9716cfecc1'
CW_BASE, QUAL_BASE = 4503606347370496, 4503606337370496
ACCEPTANCE_GAMES = 2
REPLAY_KEEP = ('seed', 'index', 'opponent', 'seat', 'episode', 'decks', 'root_decisions', 'replay_exact')
emitter = X = OUT = None


def utc(): return time.strftime('%Y-%m-%dT%H:%M:%SZ', time.gmtime())
def stop_present(): return io.lexists(JOB+'/STOP')
def hard_stop_passed(): return studytree.hard_stop_passed(JOB)


def resources_ok(disk=True):
    psi = studytree.psi_some_avg10(); mem = studytree.mem_available()
    return psi is not None and psi <= 10. and mem is not None and mem >= studytree.MEM_FLOOR and studytree.admission(JOB, 0, disk)[0]


def game_inputs(g):
    own, opp, seat = g % 5, (g // 5) % 5, g % 2
    decks = [list(X[own]) for _ in range(8)]
    decks[seat] = list(X[own]); decks[7] = list(X[opp])
    index = 56+seat
    if not (decks[index % 8] == X[own] and decks[(index//8) % 8] == X[opp] and index % 2 == seat):
        raise AssertionError('index mapping')
    return own, opp, seat, index, decks


def replay_view(directory):
    """The game's replay receipt, projected to identity fields (outcome/winner are never materialized)."""
    return io.project_json(str(directory)+'/replay.json', REPLAY_KEEP)


def check_identity(r, g, base, own, opp, seat, index):
    ep = r['episode']
    ok = (r['seed'] == base+g and r['index'] == index and r['opponent'] == 'v1' and r['seat'] == seat
          and sorted(ep['decks'][seat]) == sorted(X[own]) and sorted(ep['decks'][1-seat]) == sorted(X[opp]))
    if not ok: raise AssertionError(f'realized identity differs for game {g}')


def identity_row(directory, g, base, r):
    own, opp, seat, index, _ = game_inputs(g)
    _, msha = io.verify_sealed_dir(directory)
    return dict(g=g, seed=base+g, index=index, seat=seat, own=own, opponent=opp, roots=r['root_decisions'], manifest_sha256=msha)


def play(args):
    g, base = args
    if stop_present() or hard_stop_passed(): return dict(g=g, status='stopped')
    if not resources_ok(disk=False): return dict(g=g, status='resource_guard')
    own, opp, seat, index, decks = game_inputs(g)
    directory = f'{OUT}/game-{g:05d}'
    io.check_writable(directory, roles=('data',))
    if io.lexists(directory+'/manifest.json'):                 # resume: complete seal + realized identity
        try: io.verify_sealed_dir(directory)
        except io.Refusal as e: raise AssertionError(f'resumed game {g} fails its seal: {e}')
        r = replay_view(directory)
        check_identity(r, g, base, own, opp, seat, index)
        if studytree.raw_evidence(JOB, directory) is None:         # R9-F6/F7: reuse needs passed, in-time producer evidence
            return dict(identity_row(directory, g, base, r), status='already_sealed')
        io.rename_path(directory, f'{OUT}/unaccepted-game-{g:05d}-{int(time.time())}', roles=('data',))   # set aside
                                                                    # (outside the packer's game-* glob); played anew
    if io.lexists(directory): raise AssertionError(f'unsealed game directory present: {directory}')
    io.check_writable(directory, roles=('data',), must_not_exist=True)
    emitter.decks = lambda: [list(d) for d in decks]          # per-game input; emitter code unchanged
    t0 = time.monotonic()
    r = emitter.run_game(base+g, index, Path(directory), opponent='v1', stop=JOB+'/STOP')
    if r is None: return dict(g=g, status='stopped')
    if hard_stop_passed(): return dict(g=g, status='past_hard_stop')    # finished after the deadline: never counted
    check_identity(r, g, base, own, opp, seat, index)
    return dict(identity_row(directory, g, base, r), status='sealed', cpu_seconds=r['cpu_seconds'], wall_seconds=time.monotonic()-t0)


def pin():
    ident = multiprocessing.current_process()._identity[0]
    cores = sorted(os.sched_getaffinity(0)); os.sched_setaffinity(0, {cores[(ident-1) % len(cores)]})


def stop_workers(me):
    """TERM then KILL this run's own verified worker PIDs (never the parent, never a pattern)."""
    io.stop_owned(me['pgid'], me['leader_start'], term_grace=30, kill_grace=30, exclude=(me['pid'],))


def identity():
    ident = io.own_identity(); lead = io.proc_stat(ident['pgid'])
    return dict(pid=ident['pid'], pgid=ident['pgid'], leader_start=lead['starttime'] if lead else ident['starttime'])


def acceptance_game(g):
    """One acceptance-replay game on the qualification bank, run inside an owned worker process."""
    own, opp, seat, index, decks = game_inputs(g)
    d = f'{JOB}/data/raw-OW-acceptance/game-{g:05d}'
    io.check_writable(d, roles=('data',), must_not_exist=True)
    emitter.decks = lambda: [list(x) for x in decks]
    r = emitter.run_game(QUAL_BASE+g, index, Path(d), opponent='v1', stop=JOB+'/STOP', acceptance=True)
    if not r: return dict(g=g, status='stopped')
    if hard_stop_passed(): return dict(g=g, status='past_hard_stop')         # completed after the deadline: rejected
    check_identity(r, g, QUAL_BASE, own, opp, seat, index)
    return dict(identity_row(d, g, QUAL_BASE, r), replay_exact=bool(r.get('replay_exact')), status='sealed')


def acceptance_smoke(me, monitor=None, poll=10.0):
    """R3-F2: two emitter acceptance-replay games on the qualification bank (excluded from C' by construction), each in
    an owned worker under a supervising parent: dispatch waits for memory/PSI admission; while a game runs the parent
    polls the live guards and, on a breach (STOP incl. a dangling link, hard stop, memory, PSS, tree, disk), stops the
    worker's verified PIDs; a game finishing after the hard stop is rejected; passed also requires the deadline unmet
    at the end."""
    monitor = monitor or (lambda: studytree.monitor(JOB, own=(me['pgid'], me['leader_start'])))
    io.mkdirs(JOB+'/data/raw-OW-acceptance', roles=('data',))
    rows = []
    with ProcessPoolExecutor(max_workers=1, mp_context=multiprocessing.get_context('fork')) as pool:
        for g in range(ACCEPTANCE_GAMES):
            why = monitor()
            while why is None and not studytree.dispatch_ok()[0]:
                time.sleep(poll); why = monitor()
            if why: rows.append(dict(g=g, status='halted', reason=why)); break
            fut = pool.submit(acceptance_game, g)
            while True:
                done, _ = wait([fut], timeout=poll)
                if done: break
                why = monitor()
                if why: stop_workers(me); break
            if why:
                rows.append(dict(g=g, status='halted', reason=why)); break
            try: r = fut.result()
            except Exception as e: r = dict(g=g, status='failed', error=repr(e))
            rows.append(r)
            if r.get('status') != 'sealed': break
    passed = (len(rows) == ACCEPTANCE_GAMES and all(x.get('status') == 'sealed' and x.get('replay_exact') is True for x in rows)
              and not hard_stop_passed())
    io.write_json_once(JOB+'/data/raw-OW-acceptance-smoke.json', dict(
        schema='x4s4.ow-acceptance.v2', utc=utc(), bank='qualification', base=QUAL_BASE, games=rows, passed=passed,
        v1_sha256=V1_SHA, emitter_sha256=EMITTER_SHA, label='X4S-4 O_W acceptance smoke (excluded), NEVER ADOPTABLE'),
        roles=('data',), mode=0o444)
    return passed


def o_target():
    """R8-F4: the O_W target comes from the CURRENT authenticated O gate (guarded, receipt-bound, corpus re-verified)."""
    return studytree.authenticate_gate(JOB, 'O')[2]['rows']


def main():
    global emitter, X, OUT
    ap = argparse.ArgumentParser()
    ap.add_argument('--checkpoint', required=True)
    ap.add_argument('--count', type=int, required=True); ap.add_argument('--workers', type=int, required=True)
    ap.add_argument('--acceptance-smoke', action='store_true', help='qualification: the two acceptance-replay games')
    a = ap.parse_args()
    studytree.require_guard('collect_w')                           # R7: runs only under guard.py
    if socket.gethostname() != '127x01' or os.getpriority(os.PRIO_PROCESS, 0) < 10:
        raise SystemExit('requires 127x01 at nice >= 10')
    if not os.sched_getaffinity(0) <= set(range(50)) or not 1 <= a.workers <= min(50, len(os.sched_getaffinity(0))):
        raise SystemExit('requires cores within 0-49 and 1 <= workers <= cores')
    if not 1 <= a.count <= 6000: raise SystemExit("count must lie within bank C' (6000)")
    if stop_present() or hard_stop_passed(): raise SystemExit('STOP or hard stop')
    ok, why = studytree.admission(JOB, add=(1 if a.acceptance_smoke else a.workers)+1)
    if not ok: raise SystemExit('study admission: '+why)
    if io.sha256_file(a.checkpoint) != V1_SHA: raise SystemExit('v1 checkpoint SHA')
    import imitation.exit_r1.emitter as em
    if io.sha256_file(os.path.realpath(em.__file__)) != EMITTER_SHA: raise SystemExit('emitter SHA')
    studytree.register(JOB, 'collect-w-acceptance' if a.acceptance_smoke else 'collect-w')
    me = identity()
    emitter = em; emitter.initialize(a.checkpoint)
    X = [list(d) for d in emitter.decks()[:5]]
    from clasher.analysis.loss_review.metrics import archetype
    expect = [max((d for d in emitter.PRIOR['decks'] if archetype(d['cards']) == f), key=lambda d: d['frequency'])['cards']
              for f in ('bridge_wincon', 'siege', 'beatdown', 'bait', 'chip')]
    if X != [list(d) for d in expect]: raise SystemExit('X decks differ from the X4S run.py selection')
    if a.acceptance_smoke:
        raise SystemExit(0 if acceptance_smoke(me) else 1)
    target = o_target()
    OUT = JOB+'/data/raw-OW'
    io.mkdirs(OUT, roles=('data',))
    started, done, inflight, nxt, failed, halted = utc(), {}, {}, 0, None, None
    retry = []
    with ProcessPoolExecutor(max_workers=a.workers, mp_context=multiprocessing.get_context('fork'), initializer=pin) as pool:
        def prefix():
            total, g = 0, 0
            while g in done and done[g]['status'] in ('sealed', 'already_sealed'):
                total += done[g]['roots']; g += 1
                if total >= target: return g, total, True
            return g, total, False
        while True:
            why = studytree.monitor(JOB, own=(me['pgid'], me['leader_start']))
            if why:                                                  # in-flight hard-stop/resource path (R2-F3)
                halted = why; stop_workers(me); break
            reached = prefix()[2]
            gated = not resources_ok()
            while not (gated or reached or failed) and (retry or nxt < a.count) and len(inflight) < a.workers:
                g = retry.pop(0) if retry else nxt
                if g == nxt: nxt += 1
                inflight[pool.submit(play, (g, CW_BASE))] = g
            if not inflight:
                if gated and not (reached or failed) and (retry or nxt < a.count):
                    time.sleep(10); continue
                break
            finished, _ = wait(list(inflight), timeout=10, return_when=FIRST_COMPLETED)
            for f in finished:
                g = inflight.pop(f)
                try: r = f.result()
                except Exception as e: r = dict(g=g, status='failed', error=repr(e)); failed = failed or r
                print(json.dumps(r), flush=True)
                if r['status'] == 'resource_guard': retry.append(g)        # nothing was run; same index later
                elif r['status'] == 'past_hard_stop': halted = halted or 'hard_stop_time'
                elif r['status'] != 'stopped': done[g] = r
    n, total, reached = prefix()
    moved = []
    ok = bool(reached and not failed and not halted)
    if ok:   # pack.py globs every game-*; keep only the selected prefix in OUT (rename, never delete)
        unused = JOB+'/data/raw-OW-unused'; io.mkdirs(unused, roles=('data',))
        for name in io.listdir(OUT):
            if name.startswith('game-') and int(name.split('-')[1]) >= n:
                io.rename_path(f'{OUT}/{name}', f'{unused}/{name}', roles=('data',)); moved.append(name)
    io.write_json_once(JOB+'/data/raw-OW-selection.json', dict(
        schema='x4s4.ow-selection.v2', moved_to_unused=moved, started=started, finished=utc(), base=CW_BASE, target_roots=target,
        reached=ok, halted=halted, selected_games=list(range(n)) if ok else [], selected_roots=total if ok else 0,
        last_game_roots=done[n-1]['roots'] if ok and n else None, games=[done[g] for g in range(n)] if ok else [],
        v1_sha256=V1_SHA, emitter_sha256=EMITTER_SHA, failed=failed,
        statuses={s: sum(r['status'] == s for r in done.values()) for s in {r['status'] for r in done.values()}},
        rule='smallest contiguous index prefix with roots >= target; later games unused',
        label='X4S-4 O_W, exploration, NEVER ADOPTABLE'), roles=('data',), mode=0o444)
    raise SystemExit(0 if ok else 1)


if __name__ == '__main__':
    main()
