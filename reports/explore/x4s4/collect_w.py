"""X4S-4 matched off-policy control O_W (exploration, NEVER ADOPTABLE). r2 after Sol script review r1.

W-screen8 (no deadline) vs the exact v1 policy on the five X decks, generated by the UNCHANGED reviewed
imitation/exit_r1/emitter.py (run_game, opponent='v1'); this wrapper only chooses inputs. For bank C' game g
(seed = C'base + g) it uses the X4S index mapping: own = X[g % 5], opponent = X[(g // 5) % 5], seat = g % 2. The
emitter derives own = decks()[index % 8], other = decks()[(index // 8) % 8], seat = index % 2, so the wrapper passes
index = 56 + seat and, per game, a decks() list with X[own] at position seat and X[opponent] at position 7. X is the
emitter's first five decks() entries, which equal the X4S run.py X decks (asserted).

Outputs are fixed and confined: games in <job>/data/raw-OW/game-<g:05d>/ (the pack.py layout); the selection receipt
<job>/data/raw-OW-selection.json; unselected completed games renamed into <job>/data/raw-OW-unused/; the
qualification acceptance smoke receipt <job>/data/raw-OW-acceptance-smoke.json (its games in raw-OW-acceptance/).

Every game, fresh or resumed (Sol F6), must match its realized identity: replay seed == C'base+g, index == 56+seat,
opponent v1, seat, and both deck multisets; a resumed game's manifest must re-verify. Dispatch stops once the
contiguous completed prefix holds >= target roots (|O| from O-VERIFIED.json); the smallest such prefix is selected.
No new game is dispatched while memory PSI avg10 > 10, PSI is unreadable, MemAvailable < 24 GiB, the X4S-4 tree
holds > 70 processes or the job > 100 GB (studytree.py; the run registers its process group) (R2-11, Sol F9);
STOP (-e or -L), the study hard stop, host 127x01, nice >= 10 and cores within 0-49 are enforced. The process exits 1
if the target is not reached, a game fails, or the acceptance smoke fails (Sol F5).
"""
import argparse, datetime, hashlib, json, multiprocessing, os, socket, sys, time
from concurrent.futures import ProcessPoolExecutor, FIRST_COMPLETED, wait
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import confine, studytree                        # noqa: E402

JOB = confine.JOB
V1_SHA = 'd77005d59d6ed40ce7f9bfcfde569b54958bebf056e00653b10dcee3957272ed'
EMITTER_SHA = 'dab616517ea6b33ae1de6a34909526cf5409ec4ad71c180188d95d9716cfecc1'
CW_BASE = 4503606347370496
emitter = X = OUT = None


def utc(): return time.strftime('%Y-%m-%dT%H:%M:%SZ', time.gmtime())
def sha_file(p): return hashlib.sha256(Path(p).read_bytes()).hexdigest()
def stop_present(): return os.path.lexists(JOB/'STOP')
def hard_stop_passed():
    t = datetime.datetime.strptime((JOB/'HARD-STOP-UTC.txt').read_text().strip(), '%Y-%m-%dT%H:%M:%SZ').replace(tzinfo=datetime.timezone.utc)
    return datetime.datetime.now(datetime.timezone.utc) >= t
def psi_some_avg10():
    try: return float(Path('/proc/pressure/memory').read_text().split()[1].split('=')[1])
    except Exception: return None                    # unreadable: blocks dispatch
def mem_available():
    try: return int(next(x.split()[1] for x in Path('/proc/meminfo').read_text().splitlines() if x.startswith('MemAvailable:')))*1024
    except Exception: return 0
def resources_ok(disk=True):
    psi = psi_some_avg10()
    return psi is not None and psi <= 10. and mem_available() >= 24*2**30 and studytree.admission(JOB, disk=disk)[0]


def write_json(path, obj):
    p = confine.writable(str(path), roles=('data',)); tmp = confine.writable(str(p)+'.tmp', roles=('data',))
    tmp.write_text(json.dumps(obj, indent=2)+'\n')
    fd = os.open(tmp, os.O_RDONLY); os.fsync(fd); os.close(fd); tmp.replace(p)


def game_inputs(g):
    own, opp, seat = g % 5, (g // 5) % 5, g % 2
    decks = [list(X[own]) for _ in range(8)]
    decks[seat] = list(X[own]); decks[7] = list(X[opp])
    index = 56+seat
    if not (decks[index % 8] == X[own] and decks[(index//8) % 8] == X[opp] and index % 2 == seat):
        raise AssertionError('index mapping')
    return own, opp, seat, index, decks


def check_identity(r, g, base, own, opp, seat, index):
    ep = r['episode']
    ok = (r['seed'] == base+g and r['index'] == index and r['opponent'] == 'v1' and r['seat'] == seat
          and sorted(ep['decks'][seat]) == sorted(X[own]) and sorted(ep['decks'][1-seat]) == sorted(X[opp]))
    if not ok: raise AssertionError(f'realized identity differs for game {g}')


def play(args):
    g, base = args
    if stop_present() or hard_stop_passed(): return dict(g=g, status='stopped')
    if not resources_ok(disk=False): return dict(g=g, status='resource_guard')
    own, opp, seat, index, decks = game_inputs(g)
    directory = confine.writable(str(Path(OUT)/f'game-{g:05d}'), roles=('data',))
    if (directory/'manifest.json').exists():                  # resume: re-verify seal and identity (Sol F6)
        seal = json.loads((directory/'manifest.json').read_text())
        if not (seal.get('complete') is True and all(sha_file(directory/k) == v for k, v in seal['files'].items())):
            raise AssertionError(f'resumed game {g} fails its seal')
        r = json.loads((directory/'replay.json').read_text())
        check_identity(r, g, base, own, opp, seat, index)
        return dict(g=g, status='already_sealed', roots=r['root_decisions'])
    if directory.exists(): raise AssertionError(f'unsealed game directory present: {directory}')
    emitter.decks = lambda: [list(d) for d in decks]          # per-game input; emitter code unchanged
    t0 = time.monotonic()
    r = emitter.run_game(base+g, index, directory, opponent='v1', stop=str(JOB/'STOP'))
    if r is None: return dict(g=g, status='stopped')
    check_identity(r, g, base, own, opp, seat, index)
    return dict(g=g, status='sealed', roots=r['root_decisions'], own=own, opponent=opp, seat=seat, index=index,
                cpu_seconds=r['cpu_seconds'], wall_seconds=time.monotonic()-t0)


def pin():
    ident = multiprocessing.current_process()._identity[0]
    cores = sorted(os.sched_getaffinity(0)); os.sched_setaffinity(0, {cores[(ident-1) % len(cores)]})


def main():
    global emitter, X, OUT
    ap = argparse.ArgumentParser()
    ap.add_argument('--checkpoint', type=Path, required=True)
    ap.add_argument('--count', type=int, required=True); ap.add_argument('--workers', type=int, required=True)
    ap.add_argument('--acceptance-smoke', type=int, default=0, help='qualification: N games with emitter acceptance replay')
    a = ap.parse_args()
    if socket.gethostname() != '127x01' or os.getpriority(os.PRIO_PROCESS, 0) < 10:
        raise SystemExit('requires 127x01 at nice >= 10')
    if not os.sched_getaffinity(0) <= set(range(50)) or not 1 <= a.workers <= min(50, len(os.sched_getaffinity(0))):
        raise SystemExit('requires cores within 0-49 and 1 <= workers <= cores')
    if not 1 <= a.count <= 6000: raise SystemExit("count must lie within bank C' (6000)")
    if stop_present() or hard_stop_passed(): raise SystemExit('STOP or hard stop')
    if sha_file(a.checkpoint) != V1_SHA: raise SystemExit('v1 checkpoint SHA')
    import imitation.exit_r1.emitter as em
    if sha_file(em.__file__) != EMITTER_SHA: raise SystemExit('emitter SHA')
    emitter = em; emitter.initialize(str(a.checkpoint))
    X = [list(d) for d in emitter.decks()[:5]]
    from clasher.analysis.loss_review.metrics import archetype
    expect = [max((d for d in emitter.PRIOR['decks'] if archetype(d['cards']) == f), key=lambda d: d['frequency'])['cards']
              for f in ('bridge_wincon', 'siege', 'beatdown', 'bait', 'chip')]
    if X != [list(d) for d in expect]: raise SystemExit('X decks differ from the X4S run.py selection')
    if a.acceptance_smoke:
        acc = confine.mkdirs(str(JOB/'data'/'raw-OW-acceptance'), roles=('data',))
        rows = []
        for g in range(a.acceptance_smoke):
            own, opp, seat, index, decks = game_inputs(g)
            emitter.decks = lambda d=decks: [list(x) for x in d]
            r = emitter.run_game(CW_BASE+g, index, confine.writable(str(acc/f'game-{g:05d}'), roles=('data',), must_not_exist=True),
                                 opponent='v1', stop=str(JOB/'STOP'), acceptance=True)
            ok = bool(r and r.get('replay_exact'))
            if r: check_identity(r, g, CW_BASE, own, opp, seat, index)
            rows.append(dict(g=g, replay_exact=ok, roots=r and r['root_decisions']))
        passed = all(x['replay_exact'] for x in rows) and len(rows) == a.acceptance_smoke
        write_json(JOB/'data'/'raw-OW-acceptance-smoke.json', dict(utc=utc(), games=rows, passed=passed, v1_sha256=V1_SHA, emitter_sha256=EMITTER_SHA))
        raise SystemExit(0 if passed else 1)
    studytree.register(JOB, 'collect-w')
    target = json.loads((JOB/'data'/'O-VERIFIED.json').read_text())['rows']
    OUT = str(confine.mkdirs(str(JOB/'data'/'raw-OW'), roles=('data',)))
    started, done, inflight, nxt, failed = utc(), {}, {}, 0, None
    retry = []
    with ProcessPoolExecutor(max_workers=a.workers, mp_context=multiprocessing.get_context('fork'), initializer=pin) as pool:
        def prefix():
            total, g = 0, 0
            while g in done and done[g]['status'] in ('sealed', 'already_sealed'):
                total += done[g]['roots']; g += 1
                if total >= target: return g, total, True
            return g, total, False
        while True:
            reached = prefix()[2]
            halted = stop_present() or hard_stop_passed()
            gated = not resources_ok()
            while not (gated or halted or reached or failed) and (retry or nxt < a.count) and len(inflight) < a.workers:
                g = retry.pop(0) if retry else nxt
                if g == nxt: nxt += 1
                inflight[pool.submit(play, (g, CW_BASE))] = g
            if not inflight:
                if gated and not (halted or reached or failed) and (retry or nxt < a.count):
                    time.sleep(10); continue
                break
            finished, _ = wait(list(inflight), timeout=10, return_when=FIRST_COMPLETED)
            for f in finished:
                g = inflight.pop(f)
                try: r = f.result()
                except Exception as e: r = dict(g=g, status='failed', error=repr(e)); failed = failed or r
                print(json.dumps(r), flush=True)
                if r['status'] == 'resource_guard': retry.append(g)        # nothing was run; same index later
                elif r['status'] != 'stopped': done[g] = r
    n, total, reached = prefix()
    moved = []
    ok = bool(reached and not failed)
    if ok:   # pack.py globs every game-*; keep only the selected prefix in OUT (rename, never delete)
        unused = confine.mkdirs(str(JOB/'data'/'raw-OW-unused'), roles=('data',))
        for d in sorted(Path(OUT).glob('game-*')):
            if int(d.name.split('-')[1]) >= n:
                d.rename(confine.writable(str(unused/d.name), roles=('data',), must_not_exist=True)); moved.append(d.name)
    write_json(JOB/'data'/'raw-OW-selection.json', dict(moved_to_unused=moved, started=started, finished=utc(), base=CW_BASE,
        target_roots=target, reached=ok, selected_games=list(range(n)) if ok else [], selected_roots=total if ok else 0,
        last_game_roots=done[n-1]['roots'] if ok and n else None, v1_sha256=V1_SHA, emitter_sha256=EMITTER_SHA,
        failed=failed, statuses={s: sum(r['status'] == s for r in done.values()) for s in {r['status'] for r in done.values()}},
        rule='smallest contiguous index prefix with roots >= target; later games unused',
        label='X4S-4 O_W, exploration, NEVER ADOPTABLE'))
    raise SystemExit(0 if ok else 1)


if __name__ == '__main__':
    main()
