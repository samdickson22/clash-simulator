"""X4S-4 matched off-policy control O_W (exploration, NEVER ADOPTABLE).

W-screen8 (no deadline) vs the exact v1 policy on the five X decks, generated by the UNCHANGED
reviewed imitation/exit_r1/emitter.py (run_game, opponent='v1'); this wrapper only chooses inputs.
For bank C' game g (seed = C'base + g) it uses the X4S index mapping: own = X[g % 5],
opponent = X[(g // 5) % 5], seat = g % 2. The emitter derives own = decks()[index % 8],
other = decks()[(index // 8) % 8], seat = index % 2, so the wrapper passes index = 56 + seat
(index % 8 = seat, (index // 8) % 8 = 7) and, per game, a decks() list with X[own] at position seat
and X[opponent] at position 7. X is the emitter's own first five decks() entries, which equal the
X4S run.py X decks (asserted). The emitter's own shuffling, players, rows and sealing are untouched.

Games run in index order on a pinned single-core pool; dispatch stops once the contiguous completed
prefix holds >= target roots (|O| from O-VERIFIED.json). The selection receipt (OUT-selection.json)
names the smallest such prefix; later completed games are renamed into OUT-unused/ so pack.py sees
only the selection. STOP (-e or -L), MemAvailable < 24 GiB, host 127x01,
nice >= 10 and cores within 0-49 are enforced; no new game is dispatched while memory PSI avg10 > 10
or MemAvailable < 24 GiB (R2-11). Each game's realized (own, opponent, seat, seed, opponent=v1) is asserted. Each sealed game is
OUT/game-<g:05d>/ (the pack.py layout).
"""
import argparse, hashlib, json, multiprocessing, os, socket, sys, time
from concurrent.futures import ProcessPoolExecutor, FIRST_COMPLETED, wait
from pathlib import Path

JOB = Path('/mpac/sdicks02/jobs/clasher/x4s4-onpolicy')
V1_SHA = 'd77005d59d6ed40ce7f9bfcfde569b54958bebf056e00653b10dcee3957272ed'
EMITTER_SHA = 'dab616517ea6b33ae1de6a34909526cf5409ec4ad71c180188d95d9716cfecc1'
emitter = X = OUT = None


def utc(): return time.strftime('%Y-%m-%dT%H:%M:%SZ', time.gmtime())
def stop_present(): return os.path.lexists(JOB/'STOP')
def psi_some_avg10():
    try: return float(Path('/proc/pressure/memory').read_text().split()[1].split('=')[1])
    except Exception: return 0.
def mem_available():
    return int(next(x.split()[1] for x in Path('/proc/meminfo').read_text().splitlines() if x.startswith('MemAvailable:')))*1024


def write_json(path, obj):
    tmp = Path(str(path)+'.tmp'); tmp.write_text(json.dumps(obj, indent=2)+'\n')
    fd = os.open(tmp, os.O_RDONLY); os.fsync(fd); os.close(fd); tmp.replace(path)


def game_inputs(g):
    own, opp, seat = g % 5, (g // 5) % 5, g % 2
    decks = [list(X[own]) for _ in range(8)]
    decks[seat] = list(X[own]); decks[7] = list(X[opp])
    index = 56+seat
    if not (decks[index % 8] == X[own] and decks[(index//8) % 8] == X[opp] and index % 2 == seat):
        raise AssertionError('index mapping')
    return own, opp, seat, index, decks


def play(args):
    g, base = args
    if stop_present(): return dict(g=g, status='stopped')
    if mem_available() < 24*2**30: return dict(g=g, status='memory_guard')
    own, opp, seat, index, decks = game_inputs(g)
    emitter.decks = lambda: [list(d) for d in decks]          # per-game input; emitter code unchanged
    directory = Path(OUT)/f'game-{g:05d}'
    if (directory/'manifest.json').exists():
        r = json.loads((directory/'replay.json').read_text())
        return dict(g=g, status='already_sealed', roots=r['root_decisions'])
    t0 = time.monotonic()
    r = emitter.run_game(base+g, index, directory, opponent='v1', stop=str(JOB/'STOP'))
    if r is None: return dict(g=g, status='stopped')
    ep = r['episode']                                          # realized schedule (R2-4 Sol item): asserted
    if not (r['seat'] == seat and r['opponent'] == 'v1' and r['seed'] == base+g
            and sorted(ep['decks'][seat]) == sorted(X[own]) and sorted(ep['decks'][1-seat]) == sorted(X[opp])):
        raise AssertionError(f'realized schedule differs for game {g}')
    return dict(g=g, status='sealed', roots=r['root_decisions'], own=own, opponent=opp, seat=seat, index=index,
                cpu_seconds=r['cpu_seconds'], wall_seconds=time.monotonic()-t0)


def pin():
    ident = multiprocessing.current_process()._identity[0]
    cores = sorted(os.sched_getaffinity(0)); os.sched_setaffinity(0, {cores[(ident-1) % len(cores)]})


def main():
    global emitter, X, OUT
    ap = argparse.ArgumentParser()
    ap.add_argument('--checkpoint', type=Path, required=True); ap.add_argument('--out', type=Path, required=True)
    ap.add_argument('--base', type=int, required=True); ap.add_argument('--count', type=int, required=True)
    ap.add_argument('--target-roots', type=int, required=True); ap.add_argument('--workers', type=int, required=True)
    ap.add_argument('--acceptance-smoke', type=int, default=0, help='qualification: N games with emitter acceptance replay')
    a = ap.parse_args()
    if socket.gethostname() != '127x01' or os.getpriority(os.PRIO_PROCESS, 0) < 10:
        raise SystemExit('requires 127x01 at nice >= 10')
    if not os.sched_getaffinity(0) <= set(range(50)) or not 1 <= a.workers <= min(50, len(os.sched_getaffinity(0))):
        raise SystemExit('requires cores within 0-49 and 1 <= workers <= cores')
    if stop_present(): raise SystemExit('STOP present')
    if hashlib.sha256(a.checkpoint.read_bytes()).hexdigest() != V1_SHA: raise SystemExit('v1 checkpoint SHA')
    import imitation.exit_r1.emitter as em
    if hashlib.sha256(Path(em.__file__).read_bytes()).hexdigest() != EMITTER_SHA: raise SystemExit('emitter SHA')
    emitter = em; emitter.initialize(str(a.checkpoint))
    X = [list(d) for d in emitter.decks()[:5]]
    from clasher.analysis.loss_review.metrics import archetype
    expect = [max((d for d in emitter.PRIOR['decks'] if archetype(d['cards']) == f), key=lambda d: d['frequency'])['cards']
              for f in ('bridge_wincon', 'siege', 'beatdown', 'bait', 'chip')]
    if X != [list(d) for d in expect]: raise SystemExit('X decks differ from the X4S run.py selection')
    OUT = str(a.out); a.out.mkdir(parents=True, exist_ok=True)
    if a.acceptance_smoke:
        rows = []
        for g in range(a.acceptance_smoke):
            own, opp, seat, index, decks = game_inputs(g)
            emitter.decks = lambda d=decks: [list(x) for x in d]
            r = emitter.run_game(a.base+g, index, a.out/f'game-{g:05d}', opponent='v1', stop=str(JOB/'STOP'), acceptance=True)
            rows.append(dict(g=g, replay_exact=bool(r and r.get('replay_exact')), roots=r and r['root_decisions']))
        write_json(a.out.parent/(a.out.name+'-acceptance-smoke.json'), dict(utc=utc(), games=rows, passed=all(x['replay_exact'] for x in rows)))
        return
    started, done, inflight, nxt = utc(), {}, {}, 0
    with ProcessPoolExecutor(max_workers=a.workers, mp_context=multiprocessing.get_context('fork'), initializer=pin) as pool:
        def prefix():
            total, g = 0, 0
            while g in done and done[g]['status'] in ('sealed', 'already_sealed'):
                total += done[g]['roots']; g += 1
                if total >= a.target_roots: return g, total, True
            return g, total, False
        while True:
            reached = prefix()[2]
            # R2-11: no new O_W game while memory PSI avg10 > 10 (the R5 fit may be running beside this).
            gated = psi_some_avg10() > 10. or mem_available() < 24*2**30
            while not gated and not reached and nxt < a.count and len(inflight) < a.workers and not stop_present():
                inflight[pool.submit(play, (nxt, a.base))] = nxt; nxt += 1
            if not inflight:
                if gated and not reached and not stop_present() and nxt < a.count:
                    time.sleep(10); continue
                break
            finished, _ = wait(list(inflight), timeout=10, return_when=FIRST_COMPLETED)
            for f in finished:
                r = f.result(); done[inflight.pop(f)] = r; print(json.dumps(r), flush=True)
    n, total, reached = prefix()
    moved = []
    if reached:   # pack.py globs every game-*; keep only the selected prefix in OUT (rename, never delete)
        unused = a.out.parent/(a.out.name+'-unused'); unused.mkdir(exist_ok=True)
        for d in sorted(a.out.glob('game-*')):
            if int(d.name.split('-')[1]) >= n:
                d.rename(unused/d.name); moved.append(d.name)
    write_json(a.out.parent/(a.out.name+'-selection.json'), dict(moved_to_unused=moved,started=started, finished=utc(), base=a.base, target_roots=a.target_roots,
        reached=reached, selected_games=list(range(n)) if reached else [], selected_roots=total if reached else 0,
        last_game_roots=done[n-1]['roots'] if reached and n else None, v1_sha256=V1_SHA, emitter_sha256=EMITTER_SHA,
        completed=len(done), statuses={s: sum(r['status'] == s for r in done.values()) for s in {r['status'] for r in done.values()}},
        rule='smallest contiguous index prefix with roots >= target; later games unused',
        label='X4S-4 O_W, exploration, NEVER ADOPTABLE'))


if __name__ == '__main__':
    main()
